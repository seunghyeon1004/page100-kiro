const GLYPH_STEP = 6;
const CANVAS_ROWS = 3;

/** The text in block letters, or `undefined` when it holds a character other than A to Z, 0 to 9 and space. */
export function blockText(text: string): Canvas | undefined {
  const chars = Array.from(text);
  const glyphs: (readonly string[])[] = [];
  for (const ch of chars) {
    const glyph = Object.hasOwn(GLYPHS, ch) ? GLYPHS[ch] : undefined;
    if (glyph === undefined) return undefined;
    glyphs.push(glyph);
  }
  const pixelWidth = Math.max(0, GLYPH_STEP * chars.length - 1);
  const canvas = createCanvas(Math.max(1, Math.ceil(pixelWidth / 2)), CANVAS_ROWS);
  glyphs.forEach((glyph, n) => {
    glyph.forEach((line, row) => {
      Array.from(line).forEach((on, col) => {
        if (on === "#") setPixel(canvas, GLYPH_STEP * n + col, 1 + row);
      });
    });
  });
  return canvas;
}
